CREATE TABLE IF NOT EXISTS org_color_palettes (
  id VARCHAR PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id VARCHAR NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  palette_name TEXT NOT NULL DEFAULT 'Organization Default',
  is_preset BOOLEAN NOT NULL DEFAULT false,
  light_primary TEXT,
  light_primary_foreground TEXT,
  light_secondary TEXT,
  light_secondary_foreground TEXT,
  light_accent TEXT,
  light_accent_foreground TEXT,
  light_background TEXT,
  light_foreground TEXT,
  light_muted TEXT,
  light_muted_foreground TEXT,
  light_card TEXT,
  light_card_foreground TEXT,
  light_border TEXT,
  dark_primary TEXT,
  dark_primary_foreground TEXT,
  dark_secondary TEXT,
  dark_secondary_foreground TEXT,
  dark_accent TEXT,
  dark_accent_foreground TEXT,
  dark_background TEXT,
  dark_foreground TEXT,
  dark_muted TEXT,
  dark_muted_foreground TEXT,
  dark_card TEXT,
  dark_card_foreground TEXT,
  dark_border TEXT,
  contrast_validated BOOLEAN NOT NULL DEFAULT false,
  last_validated_at TIMESTAMP,
  is_active BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMP NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS org_color_palettes_org_idx ON org_color_palettes(organization_id);
