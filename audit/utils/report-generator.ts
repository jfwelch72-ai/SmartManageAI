import { writeFileSync } from 'fs';
import type { AuditReport, AuditCheck } from '../types';
import { ensureReportDir } from './base';

export function generateJsonReport(report: AuditReport): void {
  ensureReportDir();
  writeFileSync('audit/reports/audit-report.json', JSON.stringify(report, null, 2));
  console.log('Generated: audit/reports/audit-report.json');
}

export function generateMarkdownReport(report: AuditReport): void {
  ensureReportDir();
  
  const md = `# SmartManageAI Platform Audit Report

## Summary
- **Timestamp:** ${report.timestamp}
- **Git Commit:** ${report.gitCommit}
- **Environment:** ${report.environment}
- **Duration:** ${report.duration}ms

## Overall Results
| Metric | Count |
|--------|-------|
| Total Checks | ${report.summary.total} |
| Passed | ${report.summary.passed} |
| Failed | ${report.summary.failed} |
| Warnings | ${report.summary.warnings} |
| Skipped | ${report.summary.skipped} |

## Results by Category

${Object.entries(report.categories).map(([category, stats]) => {
  const emoji = stats!.failed > 0 ? '❌' : stats!.warnings > 0 ? '⚠️' : '✅';
  return `### ${emoji} ${category}
- Passed: ${stats!.passed}
- Failed: ${stats!.failed}
- Warnings: ${stats!.warnings}
- Skipped: ${stats!.skipped}
`;
}).join('\n')}

## Passed Checks
${report.checks.filter(c => c.status === 'pass').map(c => `- ✅ [${c.category}] ${c.name}`).join('\n') || '_None_'}

## Failed Checks
${report.checks.filter(c => c.status === 'fail').map(c => formatFailedCheck(c)).join('\n\n') || '_None_'}

## Warnings
${report.checks.filter(c => c.status === 'warn').map(c => `- ⚠️ [${c.category}] ${c.name}: ${c.message || ''}`).join('\n') || '_None_'}

## Skipped Checks
${report.checks.filter(c => c.status === 'skip').map(c => `- ⏭️ [${c.category}] ${c.name}: ${c.message || 'No reason provided'}`).join('\n') || '_None_'}

---
*Generated by SmartManageAI Audit Harness*
`;

  writeFileSync('audit/reports/audit-report.md', md);
  console.log('Generated: audit/reports/audit-report.md');
}

function formatFailedCheck(check: AuditCheck): string {
  let result = `### ❌ [${check.category}] ${check.name}`;
  if (check.message) result += `\n**Message:** ${check.message}`;
  if (check.file) result += `\n**File:** ${check.file}${check.line ? `:${check.line}` : ''}`;
  if (check.details) result += `\n**Details:** ${check.details}`;
  if (check.reproductionSteps?.length) {
    result += '\n**Reproduction Steps:**\n' + check.reproductionSteps.map((s, i) => `${i + 1}. ${s}`).join('\n');
  }
  return result;
}

