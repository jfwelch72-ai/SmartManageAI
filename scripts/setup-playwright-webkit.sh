#!/usr/bin/env bash
# Task #1866 — Make Playwright's bundled WebKit launchable inside the Replit
# dev container so cross-engine specs (e.g. e2e/takeoff-markup-undo.spec.ts)
# can be debugged locally without pushing to CI.
#
# Why this script exists
# ----------------------
# CI on Ubuntu runs `npx playwright install --with-deps webkit` which apt-gets
# the system libraries (libjpeg-turbo8, libpsl5t64, libnghttp2-14, etc.) into
# /usr/lib/x86_64-linux-gnu so Playwright's MiniBrowser wrapper can load them
# from its hard-coded LD_LIBRARY_PATH. The Replit dev container does not have
# apt — it has Nix, and `replit.nix` already pins `libjpeg8`, `libpsl`, and
# `nghttp2` (Task #1866) so the libs *are* available, but only via
# `$REPLIT_LD_LIBRARY_PATH`. The MiniBrowser bash wrapper that ships in the
# Playwright zip *overwrites* LD_LIBRARY_PATH instead of appending to it, so
# the runtime loader never sees those nix-store paths.
#
# Task #1908 — Re-verify after every Playwright/WebKit bump that those three
# libs are still missing from the bundled WebKit, and drop any entry from
# `replit.nix` that the new bundle resolves on its own. Recipe:
#   for d in minibrowser-gtk minibrowser-wpe; do
#     W="$XDG_CACHE_HOME/ms-playwright/$(ls "$XDG_CACHE_HOME/ms-playwright" | grep ^webkit- | sort -r | head -n1)/$d"
#     LD_LIBRARY_PATH="$W/lib:$W/sys/lib" \
#       env -u REPLIT_LD_LIBRARY_PATH ldd "$W/bin/MiniBrowser" \
#       | grep -E 'libjpeg\.so\.8|libpsl\.so\.5|libnghttp2\.so\.14'
#   done
# Last verified missing on webkit-2272 (Playwright 1.59.1) — all three
# `replit.nix` entries are still required.
#
# This script:
#   1. Installs Playwright's WebKit binary if it isn't already present
#      (PLAYWRIGHT_SKIP_VALIDATE_HOST_REQUIREMENTS=1 because the validator
#      uses ldd against the un-patched wrapper paths and would otherwise
#      bail before the binary is even on disk).
#   2. Patches the gtk + wpe `MiniBrowser` wrappers in-place so they preserve
#      any pre-existing LD_LIBRARY_PATH and append $REPLIT_LD_LIBRARY_PATH.
#      The patch is idempotent — the marker line `# patched-for-replit` is
#      checked first, so re-running after `npx playwright install webkit`
#      cleanly re-applies it.
#
# Pairs with the `process.env.PLAYWRIGHT_SKIP_VALIDATE_HOST_REQUIREMENTS`
# guard at the top of `playwright.config.ts`, which short-circuits the same
# pre-launch ldd validator at test time.
set -euo pipefail

PATCH_MARKER="# patched-for-replit (Task #1866) — preserve LD_LIBRARY_PATH"

# Mirror Playwright's own browsers-path resolution
# (node_modules/playwright-core/lib/server/registry/index.js):
#   $PLAYWRIGHT_BROWSERS_PATH wins, else $XDG_CACHE_HOME/ms-playwright,
#   else $HOME/.cache/ms-playwright. On Replit, XDG_CACHE_HOME is set to
#   /home/runner/workspace/.cache so caches live with the workspace.
if [[ -n "${PLAYWRIGHT_BROWSERS_PATH:-}" ]]; then
  cache_root="$PLAYWRIGHT_BROWSERS_PATH"
elif [[ -n "${XDG_CACHE_HOME:-}" ]]; then
  cache_root="$XDG_CACHE_HOME/ms-playwright"
else
  cache_root="$HOME/.cache/ms-playwright"
fi

webkit_dir="$(find "$cache_root" -maxdepth 1 -type d -name 'webkit-*' 2>/dev/null | sort -r | head -n 1 || true)"

# Task #1890 — `PLAYWRIGHT_WEBKIT_PATCH_ONLY=1` is set by the
# `playwright.global-setup.ts` self-heal hook so the per-test-run invocation
# is a no-op when WebKit isn't installed (the user might be running only
# `--project=chromium`, and we don't want to silently download ~80MB of
# WebKit on their behalf). Manual one-shot setup (no env var) keeps the
# original behavior of fetching WebKit if it's missing.
if [[ -z "$webkit_dir" ]]; then
  if [[ "${PLAYWRIGHT_WEBKIT_PATCH_ONLY:-}" == "1" ]]; then
    echo "[setup-playwright-webkit] WebKit not installed under $cache_root — skipping (PLAYWRIGHT_WEBKIT_PATCH_ONLY=1)."
    exit 0
  fi
  echo "[setup-playwright-webkit] WebKit not installed — fetching via 'npx playwright install webkit' …"
  PLAYWRIGHT_SKIP_VALIDATE_HOST_REQUIREMENTS=1 npx --yes playwright install webkit
  webkit_dir="$(find "$cache_root" -maxdepth 1 -type d -name 'webkit-*' 2>/dev/null | sort -r | head -n 1)"
fi

if [[ -z "$webkit_dir" || ! -d "$webkit_dir" ]]; then
  echo "[setup-playwright-webkit] ERROR: could not locate a webkit-* directory under $cache_root" >&2
  exit 1
fi

echo "[setup-playwright-webkit] Patching MiniBrowser wrappers under $webkit_dir"

patch_wrapper() {
  local wrapper="$1"
  if [[ ! -f "$wrapper" ]]; then
    echo "[setup-playwright-webkit] (skipping — not present: $wrapper)"
    return 0
  fi
  if grep -qF "$PATCH_MARKER" "$wrapper"; then
    echo "[setup-playwright-webkit] already patched: $wrapper"
    return 0
  fi
  chmod +w "$wrapper"
  cat > "$wrapper" <<'WRAPPER'
#!/bin/sh
# patched-for-replit (Task #1866) — preserve LD_LIBRARY_PATH
MYDIR="$(dirname $(readlink -f $0))"
export WEBKIT_EXEC_PATH="${MYDIR}/bin"
export WEBKIT_INJECTED_BUNDLE_PATH="${MYDIR}/lib"
# The original wrapper (regenerated by every `npx playwright install`) does:
#   export LD_LIBRARY_PATH="${MYDIR}/lib:${MYDIR}/sys/lib"
# which clobbers the dev container's nix-store library paths and leaves
# libjpeg.so.8 / libpsl.so.5 / libnghttp2.so.14 unresolvable. We append the
# parent shell's LD_LIBRARY_PATH and Replit's auto-managed
# REPLIT_LD_LIBRARY_PATH so those nix-store libs (provisioned via
# replit.nix's libjpeg8/libpsl/nghttp2 deps) are discoverable.
export LD_LIBRARY_PATH="${MYDIR}/lib:${MYDIR}/sys/lib${LD_LIBRARY_PATH:+:${LD_LIBRARY_PATH}}${REPLIT_LD_LIBRARY_PATH:+:${REPLIT_LD_LIBRARY_PATH}}"
exec "${MYDIR}/bin/MiniBrowser" "$@"
WRAPPER
  chmod +x "$wrapper"
  echo "[setup-playwright-webkit] patched: $wrapper"
}

patch_wrapper "$webkit_dir/minibrowser-gtk/MiniBrowser"
patch_wrapper "$webkit_dir/minibrowser-wpe/MiniBrowser"

echo "[setup-playwright-webkit] Done."
