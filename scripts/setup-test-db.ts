#!/usr/bin/env tsx
/**
 * One-shot bootstrapper for the local test database.
 *
 * What it does:
 *   1. Reads DATABASE_URL (the main dev DB connection — e.g.
 *      `postgresql://postgres:***@helium/heliumdb?sslmode=disable`).
 *   2. Connects to the server's default `postgres` admin DB and ensures a
 *      sibling test database exists (default name: `<dbname>_test`, e.g.
 *      `heliumdb_test`). Re-running is safe; it never drops an existing DB.
 *   3. Writes `.env.test` at the project root with a DATABASE_URL pointed at
 *      the test database. `server/__tests__/globalSetup.ts` auto-loads this
 *      file before its safety check, so `npm test` then "just works" without
 *      the contributor having to export anything.
 *
 * Usage:
 *   npm run test:setup
 *
 * Re-run this any time you wipe the test DB or move to a new machine.
 */
import { Client } from "pg";
import { writeFileSync, existsSync } from "node:fs";
import path from "node:path";

const SOURCE_URL = process.env.DATABASE_URL;
if (!SOURCE_URL) {
  console.error(
    "[test:setup] DATABASE_URL is not set. Open a Replit shell (where the\n" +
      "managed Postgres credentials are exported automatically) and re-run\n" +
      "`npm run test:setup`.",
  );
  process.exit(1);
}

let parsed: URL;
try {
  parsed = new URL(SOURCE_URL);
} catch (err) {
  console.error(
    `[test:setup] DATABASE_URL is not a valid URL (${(err as Error).message}).`,
  );
  process.exit(1);
}

const sourceDbName = (parsed.pathname || "").replace(/^\//, "");
if (!sourceDbName) {
  console.error("[test:setup] DATABASE_URL is missing a database name.");
  process.exit(1);
}

// Pick a sibling DB name that satisfies globalSetup's "must contain test"
// safety check. Honor TEST_DATABASE_NAME if a contributor wants something
// other than the default `<dbname>_test` (e.g. CI sandboxes).
const testDbName =
  process.env.TEST_DATABASE_NAME ||
  (sourceDbName.toLowerCase().includes("test")
    ? sourceDbName
    : `${sourceDbName}_test`);

if (!testDbName.toLowerCase().includes("test")) {
  console.error(
    `[test:setup] Refusing to use database name '${testDbName}' — it must\n` +
      "contain the substring 'test' so the destructive globalSetup safety\n" +
      "check will accept it. Set TEST_DATABASE_NAME explicitly.",
  );
  process.exit(1);
}

if (testDbName === sourceDbName) {
  console.error(
    `[test:setup] Source DATABASE_URL already targets '${sourceDbName}',\n` +
      "which contains 'test'. Refusing to point the test DB at the same\n" +
      "database as your dev DB — set TEST_DATABASE_NAME to disambiguate.",
  );
  process.exit(1);
}

async function ensureDatabaseExists(): Promise<void> {
  // Connect to the server's default `postgres` admin DB so we can issue
  // `CREATE DATABASE`. We can't issue it from inside the dev DB itself.
  const adminUrl = new URL(SOURCE_URL!);
  adminUrl.pathname = "/postgres";
  const admin = new Client({ connectionString: adminUrl.toString() });
  await admin.connect();
  try {
    const exists = await admin.query(
      "SELECT 1 FROM pg_database WHERE datname = $1",
      [testDbName],
    );
    if (exists.rowCount && exists.rowCount > 0) {
      console.log(`[test:setup] Database '${testDbName}' already exists.`);
      return;
    }
    // Identifier interpolation is safe here because we validated the name
    // above. `pg` does not parameterize DDL.
    const escaped = `"${testDbName.replace(/"/g, '""')}"`;
    await admin.query(`CREATE DATABASE ${escaped}`);
    console.log(`[test:setup] Created database '${testDbName}'.`);
  } finally {
    await admin.end();
  }
}

function writeEnvFile(): string {
  const testUrl = new URL(SOURCE_URL!);
  testUrl.pathname = `/${testDbName}`;
  const envPath = path.resolve(process.cwd(), ".env.test");
  const banner =
    "# Auto-generated by `npm run test:setup`. Safe to delete and regenerate.\n" +
    "# server/__tests__/globalSetup.ts loads this file before running tests so\n" +
    "# `npm test` targets the dedicated test database without any manual export.\n";
  const body = `DATABASE_URL=${testUrl.toString()}\n`;
  if (existsSync(envPath)) {
    console.log(`[test:setup] Overwriting existing ${envPath}.`);
  }
  writeFileSync(envPath, banner + body, { mode: 0o600 });
  return envPath;
}

async function main(): Promise<void> {
  await ensureDatabaseExists();
  const envPath = writeEnvFile();
  console.log(
    `[test:setup] Wrote ${envPath} pointing at database '${testDbName}'.`,
  );
  console.log(
    "[test:setup] Done. You can now run `npm test` — the schema will be\n" +
      "rebuilt automatically on first run (~12s) and cached on subsequent runs.",
  );
}

main().catch((err) => {
  console.error("[test:setup] Failed:", err);
  process.exit(1);
});
