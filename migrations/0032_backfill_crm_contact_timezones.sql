           WHEN 'AMERICAN SAMOA' THEN 'Pacific/Pago_Pago'
           WHEN 'MP' THEN 'Pacific/Guam'
           WHEN 'NORTHERN MARIANA ISLANDS' THEN 'Pacific/Guam'
           ELSE NULL
         END AS tz
  FROM "crm_contacts" c2
  JOIN "crm_organisations" o ON o.id = c2.organisation_id
  WHERE c2.timezone IS NULL
    AND o.state IS NOT NULL
    AND BTRIM(o.state) <> ''
) AS sub
WHERE c.id = sub.id
  AND c.timezone IS NULL
  AND sub.tz IS NOT NULL;
