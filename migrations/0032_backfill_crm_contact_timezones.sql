-- Backfill crm_contacts.timezone for legacy rows by inferring from the parent
-- crm_organisation's `state` column. Only NULL timezones are touched, so this
-- migration is idempotent and safe to re-run. Mirrors shared/timezones.ts so
-- the SQL fallback stays in sync with application logic.
--
-- A second-stage fallback that uses contact-level address columns runs in
-- the application via server/utils/ensureCrmContactTimezoneBackfill.ts —
-- those columns do not exist in the canonical schema today, so this SQL
-- file only encodes the org-state pass.

UPDATE "crm_contacts" AS c
SET "timezone" = sub.tz,
    "updated_at" = NOW()
FROM (
  SELECT c2.id AS id,
         CASE UPPER(BTRIM(o.state))
           WHEN 'AL' THEN 'America/Chicago'
           WHEN 'ALABAMA' THEN 'America/Chicago'
           WHEN 'AK' THEN 'America/Anchorage'
           WHEN 'ALASKA' THEN 'America/Anchorage'
           WHEN 'AZ' THEN 'America/Phoenix'
