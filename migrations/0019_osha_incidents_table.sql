CREATE TABLE IF NOT EXISTS osha_incidents (
  id VARCHAR PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id VARCHAR NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  case_number TEXT NOT NULL,
  project_id VARCHAR REFERENCES projects(id) ON DELETE SET NULL,
  employee_name TEXT NOT NULL,
  employee_job_title TEXT,
  date_of_injury TEXT NOT NULL,
  time_of_event TEXT,
  location_of_incident TEXT,
  event_description TEXT NOT NULL,
  injury_illness_type TEXT NOT NULL,
  body_part_affected TEXT NOT NULL,
  object_or_substance TEXT,
  treatment_type TEXT NOT NULL,
  hospital_name TEXT,
  was_hospitalized BOOLEAN NOT NULL DEFAULT false,
  days_away_from_work INTEGER DEFAULT 0,
  days_of_restricted_duty INTEGER DEFAULT 0,
  classification TEXT NOT NULL,
  is_recordable BOOLEAN NOT NULL DEFAULT true,
  resulted_in_death BOOLEAN NOT NULL DEFAULT false,
  reported_by VARCHAR REFERENCES users(id),
  reported_by_name TEXT,
  created_at TIMESTAMP NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMP NOT NULL DEFAULT NOW()
);
